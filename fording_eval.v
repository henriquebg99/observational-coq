(* Does a cast between two instances of an inductive family compute, and does
   an evaluator on the target instance compute on it?

   Hypothesis: in CICobs, constructors of inductive families are forded, so
   [eval_N : Expr N -> N] does not block on [cast (Expr nat) (Expr N) _ (NatLit 0)].

   Expected:
   1. CICobs: [cast (Expr A) (Expr B) _ t] reduces for any [A], [B] when [t] is
      a constructor, and stops at the root (forded constructor [*_cast]).
   2. CICobs: the match of [eval] fires, but its result [cast nat N _ 0] is
      stuck, as there is no rule for a cast between distinct inductive types.
   3. CICuq (after [Register Equivalences]): rule U-Cast-Equiv reduces the
      result to [N0].

   Run from the root of the repository:
     _build/install/default/bin/coqc -coqlib _build/default -allow-rewrite-rules fording_eval.v *)

(** Unary and binary natural numbers (copied from equivalences.v) *)


Inductive positive : Set := xI : positive -> positive | xO : positive -> positive | xH : positive.
Inductive N : Set := N0 : N | Npos : positive -> N.

Fixpoint double (n : nat) : nat := match n with O => O | S n => S (S (double n)) end.

Fixpoint Pos_to_nat (p : positive) : nat :=
  match p with
  | xH => S O
  | xO p => double (Pos_to_nat p)
  | xI p => S (double (Pos_to_nat p))
  end.

Fixpoint Pos_succ (p : positive) : positive :=
  match p with
  | xH => xO xH
  | xO p => xI p
  | xI p => xO (Pos_succ p)
  end.

Definition N_to_nat (m : N) : nat := match m with N0 => O | Npos p => Pos_to_nat p end.
Definition N_succ (m : N) : N := match m with N0 => Npos xH | Npos p => Npos (Pos_succ p) end.
Fixpoint N_of_nat (n : nat) : N := match n with O => N0 | S n => N_succ (N_of_nat n) end.
Definition N_double (m : N) : N := match m with N0 => N0 | Npos p => Npos (xO p) end.

Definition Pos_to_nat_succ (p : positive) : Pos_to_nat (Pos_succ p) ~ S (Pos_to_nat p).
Proof.
  induction p as [p IH | p _ |].
  - exact (ap double IH).
  - exact obseq_refl.
  - exact obseq_refl.
Defined.

Definition N_to_nat_succ (m : N) : N_to_nat (N_succ m) ~ S (N_to_nat m).
Proof.
  destruct m as [| p].
  - exact obseq_refl.
  - exact (Pos_to_nat_succ p).
Defined.

Definition nat_N_sect (n : nat) : n ~ N_to_nat (N_of_nat n).
Proof.
  induction n as [| n IH].
  - exact obseq_refl.
  - exact (obseq_trans (ap S IH) (obseq_sym (N_to_nat_succ (N_of_nat n)))).
Defined.

Definition N_succ_succ_double (m : N) : N_succ (N_succ (N_double m)) ~ N_double (N_succ m).
Proof.
  destruct m; exact obseq_refl.
Defined.

Definition N_of_nat_double (n : nat) : N_of_nat (double n) ~ N_double (N_of_nat n).
Proof.
  induction n as [| n IH].
  - exact obseq_refl.
  - exact (obseq_trans (ap (fun m => N_succ (N_succ m)) IH) (N_succ_succ_double (N_of_nat n))).
Defined.

Definition N_of_Pos_to_nat (p : positive) : N_of_nat (Pos_to_nat p) ~ Npos p.
Proof.
  induction p as [p IH | p IH |].
  - exact (obseq_trans (ap N_succ (N_of_nat_double (Pos_to_nat p))) (ap (fun m => N_succ (N_double m)) IH)).
  - exact (obseq_trans (N_of_nat_double (Pos_to_nat p)) (ap N_double IH)).
  - exact obseq_refl.
Defined.

Definition nat_N_retr (m : N) : m ~ N_of_nat (N_to_nat m).
Proof.
  destruct m as [| p].
  - exact obseq_refl.
  - exact (obseq_sym (N_of_Pos_to_nat p)).
Defined.

Define Equivalence equiv_nat_N : nat <-> N := {
  fwd := N_of_nat ;
  bwd := N_to_nat ;
  sect := nat_N_sect ;
  retr := nat_N_retr }.

(** A typed syntax (Section 2 of the paper) *)

Set Observational Inductives.

Inductive Expr : Set -> Type :=
| BoolLit : bool -> Expr bool
| NatLit  : nat -> Expr nat
| Add     : Expr nat -> Expr nat -> Expr nat
| If      : forall A : Set, Expr bool -> Expr A -> Expr A -> Expr A.

Fixpoint eval (A : Set) (e : Expr A) : A :=
  match e in Expr A return A with
  | BoolLit b => b
  | NatLit n => n
  | Add e1 e2 => eval nat e1 + eval nat e2
  | If A c t f => if eval bool c then eval A t else eval A f
  end.

Definition eval_N : Expr N -> N := eval N.

(* The forded constructors generated by the flag *)
About If_cast.     (* forall H A : Set, Expr bool -> Expr A -> Expr A -> H ~ A -> Expr H *)
About NatLit_cast. (* forall H : Set, nat -> H ~ nat -> Expr H *)

(** * 1. CICobs: the cast stops at the root, for any indices *)

Section Cast_root.
  Variables (A B : Set) (p : A ~ B) (c : Expr bool) (x y z : Expr A).

  (* On a constructor, the cast reduces to the forded constructor, and the
     subterms are left untouched *)
  Check (obseq_refl :
    cast (Expr A) (Expr B) (ap Expr p) (If A c x y) ~ If_cast B A c x y (obseq_sym p)).
  Eval cbn in cast (Expr A) (Expr B) (ap Expr p) (If A c x y).

  (* On a neutral term, the cast is stuck *)
  Eval cbn in cast (Expr A) (Expr B) (ap Expr p) z.

  (* The match of [eval] fires: the subterms are evaluated at [A], and the
     result is cast from [A] to [B].  We check the shape of the normal form
     with Ltac instead of [Check (obseq_refl : _ ~ cast A B p _)]: when the
     conversion test reduces a match on a forded constructor and the reduct
     still contains a cast, it raises an anomaly (undeclared universe, see
     the end of the file), and [Fail] swallows anomalies. *)
  Eval cbn in eval B (cast (Expr A) (Expr B) (ap Expr p) (If A c x y)).
  Goal True.
    let v := eval cbn in (eval B (cast (Expr A) (Expr B) (ap Expr p) (If A c x y))) in
    lazymatch v with
    | cast A B _ (if eval bool c then eval A x else eval A y) => idtac
    end.
  Abort.
End Cast_root.

(** * 2. CICobs: [eval_N] fires its match, then is stuck on [cast nat N _ 0] *)

(* Until the equivalences are registered, [equiv_nat_N] is only an axiom
   [nat ~ N], and no rule reduces a cast along it *)
Definition t0 : Expr N := cast (Expr nat) (Expr N) (ap Expr equiv_nat_N) (NatLit 0).

Check (obseq_refl : t0 ~ NatLit_cast N 0 (obseq_sym equiv_nat_N)).
Eval compute in eval_N t0.
Goal True.
  let v := eval compute in (eval_N t0) in
  lazymatch v with cast nat N _ 0 => idtac end.
Abort.

(* Same with a variable as the proof of [nat ~ N] *)
Section Var_proof.
  Variable q : nat ~ N.
  Goal True.
    let v := eval compute in (eval_N (cast (Expr nat) (Expr N) (ap Expr q) (NatLit 0))) in
    lazymatch v with cast nat N _ 0 => idtac end.
  Abort.
End Var_proof.

(** * 3. CICuq: rule U-Cast-Equiv reduces the leaf *)

Register Equivalences equiv_nat_N.

Check (obseq_refl : eval_N t0 ~ N0).
Eval compute in eval_N t0.

(* The proof of [nat ~ N] is irrelevant: a variable works as well *)
Check (fun q : nat ~ N =>
  obseq_refl : eval_N (cast (Expr nat) (Expr N) (ap Expr q) (NatLit 0)) ~ N0).

(* On a larger expression, the evaluation runs on unary numbers, and the
   result is converted once, at the root *)
Definition e_nat : Expr nat := If nat (BoolLit true) (Add (NatLit 2) (NatLit 4)) (NatLit 0).
Definition e_N : Expr N := cast (Expr nat) (Expr N) (ap Expr equiv_nat_N) e_nat.

Check (obseq_refl : eval_N e_N ~ Npos (xO (xI xH))).

Arguments N_of_nat : simpl never.
Arguments Nat.add : simpl never.
Eval cbn in eval_N e_N. (* = N_of_nat (2 + 4) *)

